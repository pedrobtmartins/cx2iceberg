/* big numbers and decimals arrive as text (exact); the alignment comes from the type of the column */
const NUMERIC = /^(tinyint|smallint|int|bigint|double|float|decimal)/;
function cell(v, type) {
  if (v === null || v === undefined) return h("td", { class: "null" }, "empty");
  if (typeof v === "number" || (typeof v === "string" && NUMERIC.test(type || ""))) return h("td", { class: "num" }, String(v));
  if (typeof v === "boolean") return h("td", {}, v ? "yes" : "no");
  if (typeof v === "object") {
    const flat = JSON.stringify(v);
    if (Array.isArray(v) && v.every((x) => x === null || typeof x !== "object") && flat.length <= 80) return h("td", { title: flat }, v.join(", "));
    return h("td", { class: "nested" }, h("details", {}, h("summary", {}, Array.isArray(v) ? `list of ${v.length}` : `${Object.keys(v).length} fields`),
      h("pre", {}, JSON.stringify(v, null, 2))));
  }
  return h("td", { title: String(v) }, String(v));
}

/* ------------------------------------------------------------ report */
/* The same report as the CLI's: errors (rejected documents), declared losses and warnings, counted by
   table/column/reason. Before, the studio only showed the first messages of the log. */
const KIND_CLASS = { error: "bad", declared: "declared", warning: "warn" };
const KIND_ORDER = ["error", "declared", "warning"];
const KIND_HELP = {
  error: "These documents would not be written (none of their rows, in any table).",
  declared: "Losses the configuration declares (on_error, default, where, rounding…): they go on, and are counted.",
  warning: "They go on, but are worth reviewing.",
};
function columnMarks(rep, tableName) {
  const out = {};
  (rep?.groups || []).filter((g) => g.table === tableName && g.column).forEach((g) => {
    const m = out[g.column] || (out[g.column] = { count: 0, kind: g.kind, lines: [] });
    m.count += g.count;
    if (KIND_ORDER.indexOf(g.kind) < KIND_ORDER.indexOf(m.kind)) m.kind = g.kind;
    m.lines.push(`${g.reason_label} → ${g.action_label}: ${g.count}`);
  });
  Object.values(out).forEach((m) => { m.title = m.lines.join("\n"); });
  return out;
}
function where(g) {
  return g.table ? (g.column ? `${g.table}.${g.column}` : g.table) : "(document)";
}
function place(e) {
  return `${e.file || ""}${e.document != null ? `#${e.document}` : ""}${e.row ? ` ${e.row}` : ""}`;
}
function renderReport(rep) {
  const box = $("#report");
  const groups = rep?.groups || [];
  if (!groups.length) { box.hidden = true; box.replaceChildren(); return; }
  const parts = [h("h2", {}, "Load report")];
  if (rep.rejected_total) {
    parts.push(h("p", { class: "report-rejected" }, h("strong", {}, `${rep.rejected_total} document${rep.rejected_total === 1 ? "" : "s"} rejected: `),
      rep.rejected_documents.map((d) => `${d.file}${d.document != null ? `#${d.document}` : ""} (${d.errors} error${d.errors === 1 ? "" : "s"})`).join(", ")));
  }
  KIND_ORDER.forEach((kind) => {
    const gs = groups.filter((g) => g.kind === kind);
    if (!gs.length) return;
    const total = gs.reduce((a, g) => a + g.count, 0);
    parts.push(h("div", { class: `report-kind ${KIND_CLASS[kind]}` },
      h("h3", {}, `${gs[0].kind_title} (${total})`), h("p", { class: "hint" }, KIND_HELP[kind]),
      gs.map((g) => h("details", { class: "report-group" },
        h("summary", {}, h("span", { class: "rg-where" }, where(g)), ` — ${g.reason_label} → ${g.action_label}`, h("span", { class: "rg-count" }, String(g.count))),
        h("ul", {}, g.examples.map((e) => {
          const showValue = e.value != null && !String(e.message).includes(e.value);   // the message already quotes it
          return h("li", {}, place(e) ? h("span", { class: "rg-place" }, place(e) + ": ") : null,
            showValue ? h("code", {}, e.value) : null, showValue ? " " : null, e.message);
        }))))));
  });
  box.replaceChildren(...parts);
  box.hidden = false;
}
function renderWriteCheck(problems) {
  const box = $("#write-check");
  if (!problems?.length) { box.hidden = true; box.replaceChildren(); return; }
  box.replaceChildren(h("strong", {}, "The write would be blocked (nothing would be written)"), h("ul", {}, problems.map((p) => h("li", {}, p))));
  box.hidden = false;
}

