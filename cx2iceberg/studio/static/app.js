function explodeOf(t) {
  if (!t?.explode) return null;
  return Array.isArray(t.explode) ? t.explode.join("[*].") : String(t.explode).replace(/\[\*\]$/, "");
}
function toTablePath(abs, t) {
  const E = explodeOf(t);
  if (!E) return abs;
  if (abs === E) return "$item";
  if (abs.startsWith(E + "[*].")) return abs.slice(E.length + 4);
  return "$root." + abs;
}
function toAbsPath(p, t) {
  if (!p) return p;
  const E = explodeOf(t);
  if (p.startsWith("$root.")) return p.slice(6);
  if (p === "$item") return E;
  if (E && !p.startsWith("$")) return `${E}[*].${p}`;
  return p;
}
function sourceText(c, t) {
  if (!c) return "";
  if (c.cases) return "Conditional rule (edit under Advanced)";
  if (c.template != null) return `Composed text: ${c.template}`;
  if (c.paths) return `First with a value out of ${c.paths.length} fields`;
  if ("const" in c) return c.const == null ? "Empty (field does not exist in the source)" : `Fixed value: ${short(c.const)}`;
  if (c.path === "$index") return "Position in the list";
  if (c.path === "$item") return "Each value of the list";
  if (c.path?.startsWith("$meta.")) return `Metadata: ${c.path.slice(6)}`;
  const f = state.fieldIndex[toAbsPath(c.path, t)];
  return f ? `${f.trail}` : c.path || "No source";
}
